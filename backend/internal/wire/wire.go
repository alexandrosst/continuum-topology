// Package wire writes the shapes the API puts on the wire as TypeScript, from the Go types that are encoded, so a field that is renamed
// or dropped on the server breaks the build of the page that reads it and not a screen at run time.
//
// It is a generator and nothing else: it reads types with reflection, knows no module, and is given the roots (the types a handler
// writes) by the packages that own them. Every type reachable from a root is written once, with the names its JSON tags give.
//
// What the TypeScript says follows what encoding/json does, not what a handler hopes. A field with omitempty may be missing; a pointer, a
// slice or a map without omitempty may be null (a nil slice is null, not []); a time is a string; a type with its own MarshalJSON is
// unknown, because the generator cannot see what it writes.
package wire

import (
	"fmt"
	"reflect"
	"sort"
	"strings"
	"time"
	"unicode"
)

// Root is a type a handler writes or reads. Name is the name of its TypeScript interface; empty takes the Go name (capitalised).
type Root struct {
	Name  string
	Value any
}

// Header opens the generated file.
const Header = `// Code generated by the server's tests (go test ./internal/server -run TestWire -update). DO NOT EDIT.
//
// The shapes the API puts on the wire, written from the Go types that are encoded. What each says follows encoding/json: a field with
// omitempty may be missing, a pointer, a slice or a map without it may be null, a time is an RFC 3339 string, and unknown is a value the
// server writes with its own marshaller or as a free document.
`

// Generate returns the TypeScript for the roots and everything reachable from them.
func Generate(roots []Root) (string, error) {
	g := &gen{named: map[reflect.Type]string{}, explicit: map[reflect.Type]string{}}
	for _, r := range roots {
		t := deref(reflect.TypeOf(r.Value))
		for t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
			t = deref(t.Elem())
		}
		if t.Kind() != reflect.Struct {
			return "", fmt.Errorf("wire: root %v is a %s, not a struct", t, t.Kind())
		}
		if r.Name != "" {
			if prev, ok := g.explicit[t]; ok && prev != r.Name {
				return "", fmt.Errorf("wire: %v is given two names, %s and %s", t, prev, r.Name)
			}
			g.explicit[t] = r.Name
		}
		g.visit(t)
	}
	if err := g.assignNames(); err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(Header)
	names := make([]string, 0, len(g.byName))
	for n := range g.byName {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		b.WriteString("\n")
		if err := g.write(&b, g.byName[n]); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

type gen struct {
	named    map[reflect.Type]string
	order    []reflect.Type
	explicit map[reflect.Type]string
	byName   map[string]reflect.Type
	names    map[reflect.Type]string
}

var (
	timeType = reflect.TypeOf(time.Time{})
	marshal  = reflect.TypeOf((*interface{ MarshalJSON() ([]byte, error) })(nil)).Elem()
	textM    = reflect.TypeOf((*interface{ MarshalText() ([]byte, error) })(nil)).Elem()
)

func deref(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return t
}

// custom is whether the type writes itself, so that nothing about its fields says what is on the wire.
func custom(t reflect.Type) bool {
	if t == timeType {
		return false
	}
	return t.Implements(marshal) || reflect.PointerTo(t).Implements(marshal)
}

func (g *gen) visit(t reflect.Type) {
	t = deref(t)
	switch t.Kind() {
	case reflect.Struct:
		if t == timeType || custom(t) {
			return
		}
		if t.Name() == "" { // an anonymous struct is written where it stands; what it holds is still visited
			for _, f := range fields(t) {
				g.visit(f.typ)
			}
			return
		}
		if _, seen := g.named[t]; seen {
			return
		}
		g.named[t] = ""
		g.order = append(g.order, t)
		for _, f := range fields(t) {
			g.visit(f.typ)
		}
	case reflect.Slice, reflect.Array, reflect.Map:
		g.visit(t.Elem())
	}
}

type field struct {
	json     string
	typ      reflect.Type
	omit     bool
	asString bool
}

// fields are the encoded fields of a struct, with the fields of an embedded struct without a name of its own written into it.
func fields(t reflect.Type) []field {
	var out []field
	for i := 0; i < t.NumField(); i++ {
		sf := t.Field(i)
		tag, has := sf.Tag.Lookup("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if sf.Anonymous && name == "" {
			et := deref(sf.Type)
			if et.Kind() == reflect.Struct && !custom(et) {
				out = append(out, fields(et)...)
				continue
			}
		}
		if !sf.IsExported() {
			continue
		}
		if !has || name == "" {
			name = sf.Name
		}
		f := field{json: name, typ: sf.Type}
		for _, o := range strings.Split(opts, ",") {
			switch o {
			case "omitempty", "omitzero":
				f.omit = true
			case "string":
				f.asString = true
			}
		}
		out = append(out, f)
	}
	return out
}

func pascal(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// assignNames gives each struct its name: the explicit one, else the Go name capitalised, and when two share one, the package's name
// in front of each of them that has no explicit name.
func (g *gen) assignNames() error {
	count := map[string]int{}
	for _, t := range g.order {
		if n, ok := g.explicit[t]; ok {
			count[n]++
		} else {
			count[pascal(t.Name())]++
		}
	}
	g.byName = map[string]reflect.Type{}
	g.names = map[reflect.Type]string{}
	for _, t := range g.order {
		n, ok := g.explicit[t]
		if !ok {
			n = pascal(t.Name())
			if count[n] > 1 {
				n = pascal(lastElem(t.PkgPath())) + n
			}
		}
		if prev, dup := g.byName[n]; dup && prev != t {
			return fmt.Errorf("wire: %v and %v are both called %s: give one of them a name", prev, t, n)
		}
		g.byName[n] = t
		g.names[t] = n
	}
	return nil
}

func lastElem(p string) string {
	if i := strings.LastIndex(p, "/"); i >= 0 {
		return p[i+1:]
	}
	return p
}

func (g *gen) write(b *strings.Builder, t reflect.Type) error {
	fmt.Fprintf(b, "export interface %s {\n", g.names[t])
	for _, m := range g.members(t) {
		fmt.Fprintf(b, "  %s\n", m)
	}
	b.WriteString("}\n")
	return nil
}

// members are the "key?: type" lines of a struct.
func (g *gen) members(t reflect.Type) []string {
	var out []string
	seen := map[string]bool{}
	for _, f := range fields(t) {
		if seen[f.json] {
			continue // the shallower field of the same name wins in encoding/json; embedded ones come first here, so keep the first
		}
		seen[f.json] = true
		ts, nullable := g.ts(f.typ, f.asString)
		opt := ""
		if f.omit {
			opt = "?"
		} else if nullable {
			ts += " | null"
		}
		key := f.json
		if !isIdent(key) {
			key = "'" + strings.ReplaceAll(key, "'", "\\'") + "'"
		}
		out = append(out, fmt.Sprintf("%s%s: %s", key, opt, ts))
	}
	return out
}

func isIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if !(unicode.IsLetter(r) || r == '_' || r == '$' || (i > 0 && unicode.IsDigit(r))) {
			return false
		}
	}
	return true
}

// ts is the TypeScript for t, and whether encoding/json can write it as null (a nil pointer, slice, map or interface).
func (g *gen) ts(t reflect.Type, asString bool) (string, bool) {
	nullable := false
	for t.Kind() == reflect.Pointer {
		nullable = true
		t = t.Elem()
	}
	if t == timeType {
		return "string", nullable
	}
	if custom(t) {
		return "unknown", nullable
	}
	if asString {
		return "string", nullable
	}
	switch t.Kind() {
	case reflect.String:
		return "string", nullable
	case reflect.Bool:
		return "boolean", nullable
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number", nullable
	case reflect.Interface:
		return "unknown", false // unknown already includes null
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string", true // []byte is base64
		}
		inner, n := g.ts(t.Elem(), false)
		return arrayOf(inner, n), true
	case reflect.Array:
		inner, n := g.ts(t.Elem(), false)
		return arrayOf(inner, n), nullable
	case reflect.Map:
		inner, n := g.ts(t.Elem(), false)
		if n {
			inner += " | null"
		}
		return "Record<string, " + inner + ">", true
	case reflect.Struct:
		if t.Name() == "" {
			return "{ " + strings.Join(g.members(t), "; ") + " }", nullable
		}
		return g.names[t], nullable
	}
	return "unknown", nullable
}

func arrayOf(inner string, nullable bool) string {
	if nullable || strings.Contains(inner, " ") {
		return "(" + wrapNull(inner, nullable) + ")[]"
	}
	return inner + "[]"
}

func wrapNull(inner string, nullable bool) string {
	if nullable {
		return inner + " | null"
	}
	return inner
}
